#!/bin/sh
# Writes ios/Config/Secrets.xcconfig from the Android local.properties, so both apps use the
# same TMDB and Supabase keys.
set -eu

script_dir=$(cd "$(dirname "$0")" && pwd)
properties="${1:-$script_dir/../../android/local.properties}"
output="$script_dir/../Config/Secrets.xcconfig"

if [ ! -f "$properties" ]; then
    echo "local.properties not found: $properties" >&2
    echo "Copy local.properties.template to local.properties and fill in the keys first." >&2
    exit 1
fi

read_property() {
    # Last occurrence wins, like java.util.Properties; strips surrounding whitespace
    sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*//p" "$properties" | tail -n 1 | sed 's/[[:space:]]*$//'
}

tmdb_api_key=$(read_property TMDB_API_KEY)
supabase_url=$(read_property SUPABASE_URL)
supabase_anon_key=$(read_property SUPABASE_ANON_KEY)

for name in TMDB_API_KEY SUPABASE_URL SUPABASE_ANON_KEY; do
    eval "value=\$$(echo "$name" | tr '[:upper:]' '[:lower:]')"
    if [ -z "$value" ]; then
        echo "$name is missing in $properties" >&2
        exit 1
    fi
done

# "//" starts a comment in xcconfig files
escaped_url=$(printf '%s' "$supabase_url" | sed 's#//#/$()/#')

umask 077
cat > "$output" <<XCCONFIG
// Generated by scripts/generate_secrets.sh — do not commit
TMDB_API_KEY = $tmdb_api_key
SUPABASE_URL = $escaped_url
SUPABASE_ANON_KEY = $supabase_anon_key
XCCONFIG

echo "Wrote $output"
